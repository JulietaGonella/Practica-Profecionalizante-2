// Los textos de la lógica conservan sus emojis; la interfaz los muestra sin ellos
// porque usa iconos.
export const sinEmoji = (texto = '') =>
  String(texto)
    .replace(/[\u2300-\u23FF\u2600-\u27BF\u{1F300}-\u{1FAFF}\uFE0F\u200D]/gu, '')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();

// Tono e icono visual según el estado de la orden / ítem
export const visualEstado = (estadoId) => {
  switch (Number(estadoId)) {
    case ESTADOS_ORDEN.CREADO:
      return { tone: 'warning', icon: 'clock' };
    case ESTADOS_ORDEN.EN_PROGRESO:
      return { tone: 'info', icon: 'chefHat' };
    case ESTADOS_ORDEN.LISTO_PARA_RETIRO:
      return { tone: 'orange', icon: 'bell' };
    case ESTADOS_ORDEN.REPARTIDOR_ASIGNADO:
      return { tone: 'navy', icon: 'bike' };
    case ESTADOS_ORDEN.EN_CAMINO:
      return { tone: 'navy', icon: 'navigation' };
    case ESTADOS_ORDEN.ENTREGADO:
      return { tone: 'success', icon: 'checkCircle' };
    case ESTADOS_ORDEN.CANCELADO:
      return { tone: 'error', icon: 'xCircle' };
    default:
      return { tone: 'neutral', icon: 'info' };
  }
};

export const EstadoBadge = ({ estadoId, etiqueta }) => {
  const { tone, icon } = visualEstado(estadoId);
  return <Badge tone={tone} icon={icon}>{sinEmoji(etiqueta)}</Badge>;
};

